
#!/usr/bin/env python3
"""
Obsidian XNU platform adapter — offline validation.

Target:
    Redmi Note 14 Pro 4G
    Codename: obsidian
    SoC: MediaTek MT6789

This script only inspects an Apple Device Tree.
It does not create a bootable kernel or modify a phone.
"""

import argparse
import json
import struct
import sys
from pathlib import Path


class AppleDT:
    def __init__(self, data):
        self.data = data
        self.offset = 0
        self.nodes = []

    def read_u32(self):
        if self.offset + 4 > len(self.data):
            raise ValueError("Unexpected end of data while reading uint32")

        value = struct.unpack_from("<I", self.data, self.offset)[0]
        self.offset += 4
        return value

    def read_property(self):
        if self.offset + 32 > len(self.data):
            raise ValueError("Unexpected end of data in property name")

        name = self.data[self.offset:self.offset + 32]
        self.offset += 32

        name = name.split(b"\0", 1)[0].decode(
            "ascii", errors="replace"
        )

        length = self.read_u32()

        if self.offset + length > len(self.data):
            raise ValueError(f"Property '{name}' exceeds file size")

        value = self.data[self.offset:self.offset + length]
        self.offset += (length + 3) & ~3

        if self.offset > len(self.data):
            raise ValueError("Property padding exceeds file size")

        return name, value

    def read_node(self, parent=""):
        start = self.offset

        prop_count = self.read_u32()
        child_count = self.read_u32()

        if prop_count > 100000 or child_count > 100000:
            raise ValueError("Unreasonable node property/child count")

        properties = {}

        for _ in range(prop_count):
            name, value = self.read_property()
            properties[name] = value

        node_name = properties.get("name", b"").split(
            b"\0", 1
        )[0].decode("ascii", errors="replace")

        if not node_name:
            raise ValueError("Node has no valid name property")

        path = parent + "/" + node_name if parent else "/" + node_name

        node = {
            "path": path,
            "properties": properties,
            "children": []
        }

        self.nodes.append(node)

        for _ in range(child_count):
            node["children"].append(self.read_node(path))

        node["size"] = self.offset - start
        return node

    def parse(self):
        root = self.read_node()

        if self.offset != len(self.data):
            raise ValueError(
                f"Trailing data: {len(self.data) - self.offset} bytes"
            )

        return root


def decode_string(value):
    return value.split(b"\0", 1)[0].decode(
        "ascii", errors="replace"
    )


def decode_integer(value):
    if len(value) == 4:
        return int.from_bytes(value, "big")

    if len(value) == 8:
        return int.from_bytes(value, "big")

    return None


def format_hex(value):
    if not value:
        return ""

    return "0x" + value.hex()


def main():
    parser = argparse.ArgumentParser(
        description="Offline Apple DT validator for Redmi Note 14 Pro 4G"
    )

    parser.add_argument(
        "adt",
        help="Apple Device Tree generated by convert.py"
    )

    parser.add_argument(
        "--report",
        default="obsidian-report.json",
        help="Output JSON report"
    )

    args = parser.parse_args()

    source = Path(args.adt)

    if not source.is_file():
        sys.exit(f"ERROR: File not found: {source}")

    data = source.read_bytes()

    try:
        tree = AppleDT(data)
        tree.parse()

    except Exception as exc:
        sys.exit(f"ERROR: Apple DT parsing failed: {exc}")

    paths = {
        node["path"]: node
        for node in tree.nodes
    }

    errors = []
    warnings = []

    required = [
        "/device-tree/cpus",
    ]

    for path in required:
        if path not in paths:
            errors.append(f"Missing node: {path}")

    cpus = paths.get("/device-tree/cpus")

    cpu_nodes = cpus["children"] if cpus else []

    cpu_report = []

    for cpu in cpu_nodes:
        props = cpu["properties"]

        compatible = decode_string(
            props.get("compatible", b"")
        )

        # Ignore cpu-map, idle-states and other non-CPU nodes.
        if not compatible.startswith("arm,cortex-"):
            continue

        reg = props.get("reg", b"")

        cpu_report.append({
            "path": cpu["path"],
            "compatible": compatible,
            "reg_length": len(reg),
            "reg_hex": format_hex(reg),
            "reg_value": decode_integer(reg),
            "state": decode_string(
                props.get("state", b"")
            ),
            "enable_method": decode_string(
                props.get("enable-method", b"")
            ),
            "timebase_frequency": decode_integer(
                props.get("timebase-frequency", b"")
            ),
        })

        if not props.get("state"):
            warnings.append(
                f"{cpu['path']}: missing state property"
            )

        if not reg:
            warnings.append(
                f"{cpu['path']}: missing reg property"
            )

        if not props.get("enable-method"):
            warnings.append(
                f"{cpu['path']}: missing enable-method property"
            )

    if not cpu_report:
        errors.append("No Cortex CPU nodes found")

    if len(cpu_report) != 8:
        warnings.append(
            f"Expected 8 CPU cores, found {len(cpu_report)}"
        )

    # Inspect timer information.
    timer_report = []

    timer_paths = [
        "/device-tree/timer",
        "/device-tree/soc/systimer@10017000",
    ]

    for timer_path in timer_paths:
        timer = paths.get(timer_path)

        if not timer:
            continue

        props = timer["properties"]

        timer_report.append({
            "path": timer_path,
            "compatible": decode_string(
                props.get("compatible", b"")
            ),
            "clock_frequency": decode_integer(
                props.get("clock-frequency", b"")
            ),
            "reg_hex": format_hex(
                props.get("reg", b"")
            ),
            "interrupts_hex": format_hex(
                props.get("interrupts", b"")
            ),
        })

    report = {
        "platform": "Redmi Note 14 Pro 4G",
        "codename": "obsidian",
        "soc": "MediaTek MT6789",
        "apple_dt_size": len(data),
        "node_count": len(tree.nodes),
        "cpu_count": len(cpu_report),
        "cpus": cpu_report,
        "timers": timer_report,
        "errors": errors,
        "warnings": warnings,
        "boot_ready": False,
    }

    report_path = Path(args.report)

    report_path.write_text(
        json.dumps(report, indent=2, ensure_ascii=False),
        encoding="utf-8"
    )

    print(json.dumps(report, indent=2, ensure_ascii=False))

    print(f"\nReport saved to: {report_path.resolve()}")

    if errors:
        sys.exit(1)


if __name__ == "__main__":
    main()
